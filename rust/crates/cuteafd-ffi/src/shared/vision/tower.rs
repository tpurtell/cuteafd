//! Versioned, still-image-only arithmetic facts. No executable route is implied.
use super::{VisionError, VisionSpec, NO_VISION_OFFSET as NONE};

#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct TowerNorm {
    /// 0 none, 1 LayerNorm, 2 RMSNorm.
    pub kind: u32,
    pub epsilon: f32,
    pub weight: u64,
    pub bias: u64,
}
impl Default for TowerNorm {
    fn default() -> Self {
        Self {
            kind: 0,
            epsilon: 0.0,
            weight: NONE,
            bias: NONE,
        }
    }
}
#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct TowerProjector {
    /// 0 absent, 1 two-linear MLP.
    pub kind: u32,
    /// 0 none, 1 exact GELU, 2 tanh GELU.
    pub activation: u32,
    pub input_width: u32,
    pub hidden_width: u32,
    pub output_width: u32,
    pub reserved: u32,
    pub fc1: u64,
    pub fc1_bias: u64,
    pub fc2: u64,
    pub fc2_bias: u64,
}
impl Default for TowerProjector {
    fn default() -> Self {
        Self {
            kind: 0,
            activation: 0,
            input_width: 0,
            hidden_width: 0,
            output_width: 0,
            reserved: 0,
            fc1: NONE,
            fc1_bias: NONE,
            fc2: NONE,
            fc2_bias: NONE,
        }
    }
}
/// Offsets address one admitted arena. Tables are materialized using the vendor
/// recipe, not regenerated by the native runtime. No borrowed host arrays.
#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct TowerExtension {
    pub version: u32,
    pub size: u32,
    pub block_norm_kind: u32,
    pub activation: u32,
    pub block_norm_epsilon: f32,
    pub attention_width: u32,
    pub temporal_patch: u32,
    /// 0 none, 1 raster, 2 spatial-group-major.
    pub pixel_layout: u32,
    /// 0 none, 1 duplicate still. Version 1 has no video.
    pub temporal_input: u32,
    /// 0 none, 1 split-half THW, 2 adjacent-pair WH.
    pub rotary_kind: u32,
    pub rotary_axis_dims: [u32; 3],
    pub rotated_dims: u32,
    pub passthrough_dims: u32,
    pub inv_freq: [u64; 3],
    /// 0 none, 1 divided-fixed spatial, 2 Hy4 scale-factor `(size + 0.1) / edge`
    /// over a table whose row 0 is an unused class token. Stills skip time.
    pub absolute_kind: u32,
    pub position_height: u32,
    pub position_width: u32,
    /// 0 none, 1 compiled FP32 half-pixel bilinear, BF16 load/store, 2 ATen
    /// `upsample_bilinear2d` with a scale factor (pairs with absolute_kind 2).
    pub interpolation: u32,
    pub absolute_position: u64,
    pub pre_norm: TowerNorm,
    pub final_norm: TowerNorm,
    pub spatial_merge: u32,
    /// 0 none, 1 group then project, 2 project then group then project, 3 Hy4
    /// channel-major conv grouping then project, then one checkpoint marker row
    /// (`VisionSpec::merger_extra[0]`) after every merged row.
    pub projection_order: u32,
    pub projectors: [TowerProjector; 2],
    pub post_norm: TowerNorm,
}
impl Default for TowerExtension {
    fn default() -> Self {
        Self {
            version: 1,
            size: std::mem::size_of::<Self>() as u32,
            block_norm_kind: 0,
            activation: 0,
            block_norm_epsilon: 0.0,
            attention_width: 0,
            temporal_patch: 0,
            pixel_layout: 0,
            temporal_input: 0,
            rotary_kind: 0,
            rotary_axis_dims: [0; 3],
            rotated_dims: 0,
            passthrough_dims: 0,
            inv_freq: [NONE; 3],
            absolute_kind: 0,
            position_height: 0,
            position_width: 0,
            interpolation: 0,
            absolute_position: NONE,
            pre_norm: Default::default(),
            final_norm: Default::default(),
            spatial_merge: 0,
            projection_order: 0,
            projectors: [Default::default(); 2],
            post_norm: Default::default(),
        }
    }
}
impl TowerExtension {
    pub fn validate(&self, base: &VisionSpec) -> Result<(), VisionError> {
        let fail = || VisionError::InvalidInput("invalid generic still-image tower extension");
        let extent = |offset: u64, count: u64, bytes: u64| {
            offset != NONE
                && offset % bytes == 0
                && count
                    .checked_mul(bytes)
                    .and_then(|n| offset.checked_add(n))
                    .is_some_and(|end| end <= base.weight_bytes)
        };
        let norm = |n: TowerNorm, width: u32| match n.kind {
            0 => n == TowerNorm::default(),
            1 | 2 => {
                n.epsilon.is_finite()
                    && n.epsilon > 0.0
                    && extent(n.weight, width as u64, 2)
                    && (n.bias == NONE || n.kind == 1 && extent(n.bias, width as u64, 2))
            }
            _ => false,
        };
        let projector = |p: TowerProjector| {
            if p.kind == 0 {
                return p == TowerProjector::default();
            }
            p.kind == 1
                && (1..=2).contains(&p.activation)
                && p.reserved == 0
                && p.input_width > 0
                && p.hidden_width > 0
                && p.output_width > 0
                && extent(
                    p.fc1,
                    u64::from(p.input_width) * u64::from(p.hidden_width),
                    2,
                )
                && extent(
                    p.fc2,
                    u64::from(p.hidden_width) * u64::from(p.output_width),
                    2,
                )
                && (p.fc1_bias == NONE || extent(p.fc1_bias, p.hidden_width as u64, 2))
                && (p.fc2_bias == NONE || extent(p.fc2_bias, p.output_width as u64, 2))
        };
        let hy4 = self.absolute_kind == 2;
        if hy4 != (self.projection_order == 3)
            || (hy4
                && (!matches!(base.head_dim, 72 | 96)
                    || base.patch_size != 16
                    || self.rotary_kind != 0
                    || self.pixel_layout != 1
                    || self.temporal_patch != 1
                    || self.pre_norm != TowerNorm::default()
                    || self.post_norm != TowerNorm::default()
                    || self.final_norm.kind != 2
                    || !extent(base.merger_extra[0], u64::from(base.output_width), 2)))
        {
            return Err(fail());
        }
        if self.version != 1
            || self.size != std::mem::size_of::<Self>() as u32
            || base.perception.is_some()
            || ![1, 2].contains(&self.block_norm_kind)
            || ![1, 2].contains(&self.activation)
            || !self.block_norm_epsilon.is_finite()
            || self.block_norm_epsilon <= 0.0
            || self.attention_width == 0
            || base.heads == 0
            || base.hidden == 0
            || base.output_width == 0
            || base.heads.checked_mul(base.head_dim) != Some(self.attention_width)
            || base.kv_heads != base.heads
            || ![1, 2].contains(&self.pixel_layout)
            || !matches!((self.temporal_patch, self.temporal_input), (1, 0) | (2, 1))
            || !norm(self.pre_norm, base.hidden)
            || !norm(self.final_norm, base.hidden)
            || !norm(self.post_norm, base.output_width)
            || self.spatial_merge != 2
        {
            return Err(fail());
        }
        let dims = self.rotary_axis_dims;
        let rotated = dims.iter().try_fold(0u32, |n, &d| n.checked_add(d));
        if rotated != Some(self.rotated_dims)
            || self.rotated_dims.checked_add(self.passthrough_dims) != Some(base.head_dim)
            || dims.iter().any(|d| d % 2 != 0)
            || !matches!(self.rotary_kind, 0..=2)
        {
            return Err(fail());
        }
        if (self.rotary_kind == 0 && (dims != [0; 3] || self.rotated_dims != 0))
            || (self.rotary_kind == 1 && dims.iter().any(|&d| d == 0))
            || (self.rotary_kind == 2
                && (dims[0] != 0
                    || dims[1] == 0
                    || dims[1] != dims[2]
                    || self.passthrough_dims != 0))
        {
            return Err(fail());
        }
        for (dim, offset) in dims.into_iter().zip(self.inv_freq) {
            if if dim == 0 {
                offset != NONE
            } else {
                !extent(offset, (dim / 2) as u64, 4)
            } {
                return Err(fail());
            }
        }
        match self.absolute_kind {
            0 if self.position_height == 0
                && self.position_width == 0
                && self.interpolation == 0
                && self.absolute_position == NONE => {}
            kind @ (1 | 2)
                if self.position_height > 0
                    && self.position_width > 0
                    && self.interpolation == kind
                    && u64::from(self.position_height)
                        .checked_mul(u64::from(self.position_width))
                        .and_then(|n| n.checked_add(u64::from(kind == 2)))
                        .and_then(|n| n.checked_mul(u64::from(base.hidden)))
                        .is_some_and(|n| extent(self.absolute_position, n, 2)) => {}
            _ => return Err(fail()),
        }
        let [first, second] = self.projectors;
        let grouped = u32::checked_mul(self.spatial_merge, self.spatial_merge).ok_or_else(fail)?;
        if !projector(first) || !projector(second) || first.kind != 1 {
            return Err(fail());
        }
        match self.projection_order {
            1 | 3 if base.hidden.checked_mul(grouped) == Some(first.input_width)
                && first.output_width == base.output_width
                && second.kind == 0 => {}
            2 if first.input_width == base.hidden
                && second.kind == 1
                && first.output_width.checked_mul(grouped) == Some(second.input_width)
                && second.output_width == base.output_width => {}
            _ => return Err(fail()),
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    pub(super) fn specimen() -> VisionSpec {
        let projector = TowerProjector {
            kind: 1,
            activation: 1,
            input_width: 16,
            hidden_width: 8,
            output_width: 8,
            fc1: 256,
            fc2: 512,
            ..Default::default()
        };
        VisionSpec {
            hidden: 4,
            heads: 1,
            kv_heads: 1,
            head_dim: 4,
            output_width: 8,
            weight_bytes: 2048,
            tower: Some(TowerExtension {
                block_norm_kind: 2,
                activation: 2,
                block_norm_epsilon: f32::EPSILON,
                attention_width: 4,
                temporal_patch: 1,
                pixel_layout: 1,
                rotary_kind: 2,
                rotary_axis_dims: [0, 2, 2],
                rotated_dims: 4,
                inv_freq: [NONE, 0, 4],
                spatial_merge: 2,
                projection_order: 1,
                projectors: [projector, Default::default()],
                ..Default::default()
            }),
            ..Default::default()
        }
        .with_depth(1)
    }
    #[test]
    fn optional_extension_is_owned_without_moving_existing_prefix() {
        let base = specimen();
        let raw = base.raw().unwrap();
        assert_eq!(raw.storage_abi, 5);
        assert!(raw.perception.is_null());
        assert_eq!(raw.tower, raw._tower.as_deref().unwrap() as *const _);
        let moved = raw;
        assert_eq!(moved.tower, moved._tower.as_deref().unwrap() as *const _);
        assert_eq!(moved._tower.unwrap().size, 304);
        assert!(VisionSpec::default()
            .with_depth(1)
            .raw()
            .unwrap()
            .tower
            .is_null());
    }
    #[test]
    fn malformed_extension_is_refused_before_native_registration() {
        for fault in 0..18 {
            let mut base = specimen();
            let tower = base.tower.as_mut().unwrap();
            match fault {
                0 => tower.version = 2,
                1 => tower.size = 303,
                2 => tower.activation = 3,
                3 => tower.block_norm_epsilon = f32::NAN,
                4 => tower.rotary_axis_dims[1] = 3,
                5 => tower.passthrough_dims = 1,
                6 => tower.temporal_input = 2,
                7 => tower.inv_freq[1] = 2048,
                8 => tower.inv_freq[1] = 1,
                9 => tower.projectors[0].input_width = 4,
                10 => tower.projectors[0].reserved = 1,
                11 => {
                    tower.pre_norm = TowerNorm {
                        kind: 2,
                        epsilon: 1e-5,
                        weight: 0,
                        bias: 8,
                    }
                }
                12 => tower.absolute_kind = 1,
                13 => tower.projectors[1].fc1 = 0,
                14 => tower.spatial_merge = 0,
                15 => tower.projectors[0].fc1 = u64::MAX - 1,
                16 => base.heads = u32::MAX,
                _ => base.perception = Some(super::super::PerceptionSpec::default()),
            }
            assert!(base.raw().is_err(), "fault {fault}");
        }
    }
}
