"""Offline operator diagnostic using real Pro prefix operands and sealed AOTs.

Opt in with CUTEAFD_V4_LAYOUT_DIAGNOSTIC=1, CUTEAFD_V4_LAYOUT_ARTIFACTS,
CUTEAFD_V4_LAYOUT_SNAPSHOT, CUTEAFD_V4_LAYOUT_REFERENCE and
CUTEAFD_V4_LAYOUT_OUTPUT. This is not a serving or benchmark driver. The
prefix is generated by the official reference's first two blocks; layer 2
attention uses the serving checkpoint's native weights, not random operands.
"""
