def test_real_pro_attention_layouts_against_fp64():
    if os.environ.get("CUTEAFD_V4_LAYOUT_DIAGNOSTIC") != "1":
        pytest.skip("offline CUDA/checkpoint diagnostic is opt-in")
    import torch

    reference_dir = ROOT / "python/reference/families/deepseek_v4"
    sys.path.insert(0, str(reference_dir))
    sys.path.insert(0, str(ROOT / "third_party/sparkinfer"))
    import golden
    import kernel_torch as kt
    from b12x_model import Config, build_prefill_metadata, rope_cos_sin
    from b12x.attention._shared.mla.compressed_reference import (
        unpack_compressed_sparse_mla_kv_cache_reference as unpack,
    )
    from shape_invariant import install

    torch.cuda.set_device(0)
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.set_default_dtype(torch.bfloat16)
    torch.set_default_device("cuda")
    install()
    snapshot = Path(os.environ["CUTEAFD_V4_LAYOUT_SNAPSHOT"])
    official = Path(os.environ["CUTEAFD_V4_LAYOUT_REFERENCE"])
    artifacts = Path(os.environ["CUTEAFD_V4_LAYOUT_ARTIFACTS"])
    output = Path(os.environ["CUTEAFD_V4_LAYOUT_OUTPUT"])
    output.mkdir(parents=True, exist_ok=True)
    raw = json.loads((snapshot / "config.json").read_text())
    assert raw["hidden_size"] == 7168 and raw["num_attention_heads"] == 128
    assert raw["compress_ratios"][2] == 4
    cfg = Config.from_snapshot(official)
    assert cfg.dim == raw["hidden_size"] and cfg.n_heads == raw["num_attention_heads"]
    assert cfg.index_topk == raw["index_topk"]
    text = ("Implement a bounded asynchronous queue in Rust. Preserve cancellation, "
            "backpressure and FIFO ordering. Include tests for partial failure and shutdown. ") * 10
    from tokenizers import Tokenizer
    tokens = Tokenizer.from_file(str(official / "tokenizer.json")).encode(text).ids[:160]
    assert len(tokens) == 160
    ref = golden.import_reference(official)
    args = ref.ModelArgs(**json.loads((official / "inference/config.json").read_text()),
                         max_batch_size=1, max_seq_len=256)
    ref.world_size, ref.rank = 1, 0
    ref.default_dtype = torch.float8_e4m3fn if args.dtype == "fp8" else torch.bfloat16
    ref.scale_fmt = "ue8m0" if args.scale_dtype == "fp8" else args.scale_fmt
    ref.scale_dtype = torch.float8_e8m0fnu if args.scale_dtype == "fp8" else torch.float32
    reference_weights = golden.Weights(official)
    ids = torch.tensor([tokens], dtype=torch.long)
    with torch.inference_mode():
        embed = ref.ParallelEmbedding(args.vocab_size, args.dim)
        golden.load_module(embed, reference_weights, "embed.")
        stream = embed(ids).unsqueeze(2).repeat(1, 1, args.hc_mult, 1)
        del embed
        for layer in range(2):
            block = ref.Block(layer, args)
            golden.load_module(block, reference_weights, f"layers.{layer}.")
            stream = block(stream, 0, ids)
            del block
            golden.release_checkpoint(torch.cuda, reference_weights)
            print(f"real-prefix reference layer={layer} complete", flush=True)
    torch.save({"tokens": tokens, "stream": stream.cpu(), "reference": str(official),
                "snapshot": str(snapshot)}, output / "prefix.pt")
    del reference_weights
    torch.cuda.empty_cache()

    manifest_path = artifacts / "PROGRAMS.json"
    manifest = json.loads(manifest_path.read_text())
    entries = {p["name"]: p for p in manifest["programs"]}
    lib = C.CDLL(str(artifacts / "libcuteafd_native.so"))

    class Info(C.Structure):
        _fields_ = [("name", C.c_char * 64), ("pointers", C.c_uint32),
                    ("scalars", C.c_uint32), ("kinds", C.c_char * 16)]

    lib.cuteafd_dsv4_program_count.restype = C.c_uint32
    lib.cuteafd_dsv4_program_info.argtypes = [C.c_uint32, C.POINTER(Info)]
    lib.cuteafd_dsv4_program_load.argtypes = [C.c_uint32]
    lib.cuteafd_dsv4_program_launch.argtypes = [C.c_uint32, C.POINTER(C.c_void_p),
                                             C.POINTER(C.c_uint64), C.c_void_p]
    indexes = {}
    for index in range(lib.cuteafd_dsv4_program_count()):
        info = Info()
        assert lib.cuteafd_dsv4_program_info(index, C.byref(info)) == 0
        name = info.name.decode()
        assert len(entries[name]["pointers"]) == info.pointers
        indexes[name] = index
    sms = torch.cuda.get_device_properties(0).multi_processor_count
    for entry in entries.values():
        if entry.get("card_plans"):
            plan = next(p for p in entry["card_plans"] if p["sm_count"] == (188 if sms >= 188 else 170))
            entry["geometry"] = plan["geometry"]

    def launch(name, operands, scalars):
        entry = entries[name]
        assert len(scalars) == len(entry["scalars"])
        assert all(operands[p["name"]].is_contiguous() for p in entry["pointers"])
        pointers = (C.c_void_p * len(entry["pointers"]))(
            *[operands[p["name"]].data_ptr() for p in entry["pointers"]])
        values = (C.c_uint64 * len(scalars))(*scalars)
        assert lib.cuteafd_dsv4_program_load(indexes[name]) == 0
        assert lib.cuteafd_dsv4_program_launch(indexes[name], pointers, values,
                                             torch.cuda.current_stream().cuda_stream) == 0
        torch.cuda.synchronize()

    def scratch(name):
        return torch.zeros(entries[name]["scratch_bytes_at_capacity"].get("scratch", 16),
                           dtype=torch.uint8)

    weights = golden.Weights(snapshot)
    hashes = {}

    def get(suffix):
        name = "layers.2." + suffix
        tensor = weights.get(name).cuda().contiguous()
        hashes[name] = hashlib.sha256(tensor.cpu().view(torch.uint8).numpy().tobytes()).hexdigest()
        return tensor

    def scales(scale):
        scale = scale.contiguous().view(torch.uint8)
        n, k = scale.shape
        dest = torch.empty(n * k * 512, dtype=torch.uint8)
        launch("dsv4p_block_fp8_scale_prep", {"scale": scale, "scale_mma": dest}, [n, k])
        return dest

    def dequant(weight, scale):
        return weight.double() * scale.float().double().repeat_interleave(128, 0).repeat_interleave(128, 1)

    def quant(x, block=128):
        q, s = kt.act_quant(x, block_size=block, scale_fmt="ue8m0")
        return (q.double().reshape(*s.shape, block) * s.double().unsqueeze(-1)).reshape(x.shape)

    def norm(x, w=None):
        out = x.double() * (x.double().square().mean(-1, keepdim=True) + 1e-6).rsqrt()
        return out if w is None else out * w.double()

    def rope(x, positions, inverse=False):
        cs = cos_sin[positions].double()
        shape = [len(positions)] + [1] * (x.ndim - 2) + [32]
        c, s = cs[:, :32].view(shape), cs[:, 32:].view(shape)
        if inverse:
            s = -s
        pairs = x.double()[..., -64:].reshape(*x.shape[:-1], 32, 2)
        a, b = pairs[..., 0], pairs[..., 1]
        out = x.double().clone()
        out[..., -64:] = torch.stack((a*c-b*s, a*s+b*c), -1).flatten(-2)
        return out

    metrics = []

    def metric(op, layers, heads, reference, **extra):
        def error(x):
            x, r = x.double(), reference.double()
            assert x.shape == r.shape and bool(torch.isfinite(x).all())
            difference = x - r
            return {"max_abs": difference.abs().max().item(),
                    "rel_l2": (difference.norm()/r.norm().clamp_min(1e-30)).item()}
        row = {"op": op, "layers": error(layers), "heads": error(heads), **extra}
        metrics.append(row)
        print(json.dumps(row), flush=True)
        (output / "metrics.json").write_text(json.dumps(metrics, indent=2))

    rows = len(tokens)
    meta = build_prefill_metadata(rows, stream.device, index_topk=1024)
    cos_sin = rope_cos_sin(cfg, 4, 256, stream.device)
    residual = stream[0].contiguous()
    fn, scale, base, nw = [get(x) for x in ("hc_attn_fn", "hc_attn_scale", "hc_attn_base", "attn_norm.weight")]
    post, comb, hidden = torch.empty(rows, 4, dtype=torch.float32), torch.empty(rows, 4, 4, dtype=torch.float32), torch.empty(rows, 7168)
    launch("dsv4p_mhc_pre", dict(residual=residual, fn=fn, scale=scale, base=base, norm=nw,
           post=post, comb=comb, y=hidden, scratch=scratch("dsv4p_mhc_pre")), [rows])
    # mHC is identical for the two placements. Its output is the shared
    # real-prefix operand; compare following operators locally at their inputs.
    qa, qas, qb, qbs, kvw, kvs, qn, kvn = [get("attn." + x) for x in
        ("wq_a.weight", "wq_a.scale", "wq_b.weight", "wq_b.scale", "wkv.weight", "wkv.scale", "q_norm.weight", "kv_norm.weight")]
    qkvw = torch.cat((qa.view(torch.uint8), kvw.view(torch.uint8))).view(torch.float8_e4m3fn)
    qkvs = torch.cat((qas.view(torch.uint8), kvs.view(torch.uint8))).view(qas.dtype)
    common = dict(hidden=hidden, positions=meta.positions, main_slots=meta.main_slots, cos_sin=cos_sin,
                  w_qkv=qkvw, w_qkv_scale=scales(qkvs), q_norm=qn, kv_norm=kvn)
    producers = []
    for rank in [-1, 0, 1]:
        n = 128 if rank == -1 else 64
        lo, hi = (0, 65536) if rank == -1 else (rank*32768, (rank+1)*32768)
        name = f"dsv4p{'2' if rank >= 0 else ''}_producer_m4096"
        result = dict(common, w_q=qb[lo:hi].contiguous(), w_q_scale=scales(qbs[lo//128:hi//128]),
                      main_kv_cache=torch.zeros(meta.main_pages, 149760, dtype=torch.uint8),
                      query=torch.empty(rows, n, 512), q_rank=torch.empty(rows, 1536), scratch=scratch(name))
        launch(name, result, [rows])
        result["raw_qkv"] = result["scratch"][:rows*2048*2].view(torch.bfloat16).reshape(rows, 2048).clone()
        producers.append(result)
    full, h0, h1 = producers
    exact_qkv = quant(hidden) @ dequant(qkvw, qkvs).t()
    metric("qkv_projection", full["raw_qkv"], h0["raw_qkv"], exact_qkv)
    assert torch.equal(full["raw_qkv"], h0["raw_qkv"]) and torch.equal(h0["raw_qkv"], h1["raw_qkv"])
    metric("q_rank_norm", full["q_rank"], h0["q_rank"], norm(full["raw_qkv"][:, :1536], qn))
    qraw64 = quant(full["q_rank"]) @ dequant(qb, qbs).t()
    qref = rope(norm(qraw64.bfloat16().reshape(rows, 128, 512)), meta.positions)
    head_query = torch.cat((h0["query"], h1["query"]), 1)
    metric("q_projection_norm_rope", full["query"], head_query, qref)
    kvref = rope(norm(full["raw_qkv"][:, 1536:], kvn).bfloat16(), meta.positions)
    main_kv = torch.cat(unpack(full["main_kv_cache"], page_size=256, n_tokens=rows), -1)
    head_kv = torch.cat(unpack(h0["main_kv_cache"], page_size=256, n_tokens=rows), -1)
    metric("kv_norm_rope_cache", main_kv, head_kv, kvref)
    assert torch.equal(full["main_kv_cache"], h0["main_kv_cache"]) and torch.equal(h0["main_kv_cache"], h1["main_kv_cache"])

    c = meta.compress[4]
    joint = torch.cat([get("attn."+x+".weight") for x in
                      ("compressor.wkv", "compressor.wgate", "indexer.compressor.wkv", "indexer.compressor.wgate")])
    comp_name = "dsv4p_compressor_prefill_c4"
    comp = dict(hidden=hidden, active_groups=c["active_groups"], group_source_starts=c["group_source_starts"],
                group_rope_positions=c["group_rope_positions"], compressed_slots=c["compressed_slots"],
                active_sequences=c["active_sequences"], sequence_offsets=c["sequence_offsets"],
                state_sequence_ids=c["state_sequence_ids"], cos_sin=cos_sin, joint_projection=joint,
                main_ape=get("attn.compressor.ape"), main_norm=get("attn.compressor.norm.weight"),
                compressed_cache=torch.zeros(c["pages"], 37440, dtype=torch.uint8),
                main_kv_state=torch.zeros(1, 16, 1024, dtype=torch.float32),
                main_score_state=torch.zeros(1, 16, 1024, dtype=torch.float32),
                index_ape=get("attn.indexer.compressor.ape"), index_norm=get("attn.indexer.compressor.norm.weight"),
                index_cache=torch.zeros(c["pages"], 8448, dtype=torch.uint8),
                index_kv_state=torch.zeros(1, 16, 256, dtype=torch.float32),
                index_score_state=torch.zeros(1, 16, 256, dtype=torch.float32), scratch=scratch(comp_name))
    launch(comp_name, comp, [rows, c["groups"], 1])
    projected = comp["scratch"][:rows*2560*2].view(torch.bfloat16).reshape(rows, 2560)
    metric("compressor_joint_projection_shared", projected, projected, hidden.double() @ joint.double().t(), shared=True)

    def pool_reference(values, scores, ape, weight, width):
        groups = rows//4
        v = values.double().reshape(groups, 4, 2*width)
        s = scores.double().reshape(groups, 4, 2*width) + ape.double()
        vv = torch.zeros(groups, 8, width, dtype=torch.float64)
        ss = torch.full_like(vv, -math.inf)
        vv[:, 4:], ss[:, 4:] = v[:, :, width:], s[:, :, width:]
        vv[1:, :4], ss[1:, :4] = v[:-1, :, :width], s[:-1, :, :width]
        pooled = (vv * ss.softmax(1)).sum(1).bfloat16()
        return rope(norm(pooled, weight).bfloat16(), torch.arange(groups, dtype=torch.int64)*4)

    comp_kv = torch.cat(unpack(comp["compressed_cache"], page_size=64, n_tokens=c["groups"]), -1)
    cref = pool_reference(projected[:, :1024], projected[:, 1024:2048], comp["main_ape"], comp["main_norm"], 512)
    metric("compressor_pool_norm_rope_cache_shared", comp_kv, comp_kv, cref, shared=True)
    iref = pool_reference(projected[:, 2048:2304], projected[:, 2304:], comp["index_ape"], comp["index_norm"], 128).bfloat16()
    iref = kt.hadamard_transform(iref, 128**-0.5).bfloat16()
    kt.fp4_act_quant(iref, inplace=True)
    ik = comp["index_cache"][:, :8192].contiguous().view(torch.float8_e4m3fn).float().reshape(-1, 128)[:c["groups"]]
    ikscale = comp["index_cache"][:, 8192:].contiguous().view(torch.float32).reshape(-1)[:c["groups"]]
    ik = ik * ikscale[:, None]
    metric("index_compressor_pool_rope_hadamard_qat_cache_shared", ik, ik, iref.double(), shared=True)
    index_name = "dsv4p_index_producer_m4096"
    iw, isc, ip = [get("attn.indexer."+x) for x in ("wq_b.weight", "wq_b.scale", "weights_proj.weight")]
    index = dict(q_rank=full["q_rank"], hidden=hidden, positions=meta.positions, cos_sin=cos_sin,
                 w_q=iw, w_q_scale=scales(isc), w_proj=ip, query=torch.empty(rows, 64, 128, dtype=torch.float8_e4m3fn),
                 head_weights=torch.empty(rows, 64, dtype=torch.float32), scratch=scratch(index_name))
    launch(index_name, index, [rows])
    iraw = index["scratch"][:rows*8192*2].view(torch.bfloat16).reshape(rows, 8192)
    metric("index_query_projection_shared", iraw, iraw, quant(full["q_rank"]) @ dequant(iw, isc).t(), shared=True)
    irot = rope(iraw.reshape(rows, 64, 128), meta.positions).bfloat16()
    iq = kt.hadamard_transform(irot, 128**-0.5).bfloat16()
    kt.fp4_act_quant(iq, inplace=True)
    metric("index_query_rope_hadamard_qat_shared", index["query"].float(), index["query"].float(), iq.double(), shared=True)
    hwref = (hidden.double() @ ip.double().t()) * (128**-0.5*64**-0.5)
    metric("index_head_weights_shared", index["head_weights"], index["head_weights"], hwref, shared=True)
    selected = torch.empty(rows, 1024, dtype=torch.int32)
    top_name = "dsv4p_index_topk_prefill_m4096"
    top = dict(q_fp8=index["query"], weights=index["head_weights"], index_k_cache=comp["index_cache"],
               page_table=torch.arange(c["pages"], dtype=torch.int32), cache_lengths=c["visible"],
               output_indices=selected, scratch=scratch(top_name))
    launch(top_name, top, [rows, c["pages"], c["pages"]])
    # This bounded prefix has < topk completed groups. Every causal group must
    # occur once; ordering is deliberately retained from the production indexer.
    for row in range(rows):
        valid = selected[row][selected[row] >= 0].tolist()
        assert sorted(valid) == list(range((row+1)//4))

    sink = get("attn.attn_sink").float()
    attention = {}
    selected_rows = torch.tensor([127, 128, 143, 159], dtype=torch.int64)
    common_a = dict(swa_cache=full["main_kv_cache"], swa_indices=meta.swa_indices,
                    swa_lengths=meta.swa_lengths, indexed_cache=comp["compressed_cache"],
                    indexed_indices=selected, indexed_lengths=c["indexed_lengths"])

    def core_reference(query, row):
        sw = meta.swa_indices[row, :int(meta.swa_lengths[row])].long()
        ix = selected[row, :int(c["indexed_lengths"][row])].long()
        values = torch.cat((main_kv[sw], comp_kv[ix])).double()
        scores = query.double() @ values.t() * 512**-0.5
        lse = torch.logsumexp(torch.cat((scores, sink.double()[:, None]), -1), -1)
        probabilities = (scores-lse[:, None]).exp()
        return probabilities @ values, lse/math.log(2), scores, probabilities

    for route in ["prefill", "decode"]:
        outputs = []
        scratches = []
        for rank in [-1, 0, 1]:
            n, lo = (128, 0) if rank == -1 else (64, rank*64)
            query = full["query"] if rank == -1 else head_query[:, lo:lo+n].contiguous()
            operands = dict(common_a, q=query, attn_sink=sink[lo:lo+n].contiguous(), out=torch.empty(rows, n, 512))
            if route == "decode":
                operands = {k: (v[selected_rows].contiguous() if k in ["q", "swa_indices", "swa_lengths", "indexed_indices", "indexed_lengths"] else v)
                            for k, v in operands.items()}
                operands["out"] = torch.empty(len(selected_rows), n, 512)
            name = f"dsv4p{'2' if rank >= 0 else ''}_sparse_mla_{route}_c4_m{'4096' if route == 'prefill' else '64'}"
            operands["scratch"] = scratch(name)
            launch(name, operands, [operands["q"].shape[0]])
            outputs.append(operands["out"])
            scratches.append(operands["scratch"])
        whole, split = outputs[0], torch.cat(outputs[1:], 1)
        refs, lses, scores, probs = zip(*[core_reference(full["query"][row], int(row)) for row in selected_rows])
        reference = torch.stack(refs)
        if route == "prefill":
            metric("attention_prefill", whole[selected_rows], split[selected_rows], reference)
            lse_full = scratches[0][:rows*128*4].view(torch.float32).reshape(rows, 128)[selected_rows]
            lse_heads = torch.cat([s[:rows*64*4].view(torch.float32).reshape(rows, 64) for s in scratches[1:]], 1)[selected_rows]
            # Prefill exposes sink-inclusive base-2 LSE; decode exposes sink-free partials.
            metric("attention_prefill_lse", lse_full, lse_heads, torch.stack(lses))
        else:
            metric("attention_decode", whole, split, reference)
            # Partial LSE is sink-free. Logsumexp over splits followed by the
            # sink reconstructs the exposed denominator without changing it.
            merged_lse = []
            for rank, arena in zip([-1, 0, 1], scratches):
                n, lo = (128, 0) if rank == -1 else (64, rank*64)
                name = f"dsv4p{'2' if rank >= 0 else ''}_sparse_mla_decode_c4_m64"
                splits = entries[name]["geometry"]["num_splits"]
                count = len(selected_rows)
                offset = ((count*n*splits*512*2+1023)//1024)*1024
                partial_lse = arena[offset:offset+count*n*splits*4].view(torch.float32).reshape(count, n, splits)
                sink_plane = sink[lo:lo+n].double()[None, :, None]/math.log(2)
                planes = torch.cat((partial_lse.double(), sink_plane.expand(count, -1, -1)), -1)
                merged_lse.append(torch.logsumexp(planes*math.log(2), -1)/math.log(2))
            metric("attention_decode_lse_combine", merged_lse[0], torch.cat(merged_lse[1:], 1), torch.stack(lses))
        # Scores/softmax have no native external buffer. These derived metrics
        # test operand equivalence in FP64; they are not kernel-internal taps.
        for j, row in enumerate(selected_rows):
            _, _, hscores, hprobs = core_reference(head_query[row], int(row))
            metric(f"attention_scores_operands_row{int(row)}", scores[j], hscores, scores[j], derived=True)
            metric(f"attention_softmax_operands_row{int(row)}", probs[j], hprobs, probs[j], derived=True)
        attention[route] = (whole, split)

    wa, was, wb, wbs = [get("attn."+x) for x in ("wo_a.weight", "wo_a.scale", "wo_b.weight", "wo_b.scale")]
    wa64 = dequant(wa, was).reshape(16, 1024, 4096)
    wb64 = dequant(wb, wbs)

    def mxfp8(values, scale_bytes, block=32):
        exponents = scale_bytes.to(torch.int32)-127
        scales64 = torch.ldexp(torch.ones_like(exponents, dtype=torch.float64), exponents)
        return (values.double().reshape(*scales64.shape, block)*scales64[..., None]).reshape(values.shape)

    for route, (whole, split) in attention.items():
        count = rows if route == "prefill" else len(selected_rows)
        positions = meta.positions if route == "prefill" else meta.positions[selected_rows].contiguous()
        results, intermediates, qas_in, qbs_in = [], [], [], []
        for rank in [-1, 0, 1]:
            groups, lo = (16, 0) if rank == -1 else (8, rank*8)
            name = f"dsv4p{'2' if rank >= 0 else ''}_wo_m{'4096' if route == 'prefill' else '64'}"
            operands = dict(o=(whole if rank == -1 else whole[:, lo*8:(lo+groups)*8].contiguous()),
                            positions=positions, cos_sin=cos_sin, wo_a=wa[lo*1024:(lo+groups)*1024].contiguous(),
                            wo_a_scale=scales(was[lo*8:(lo+groups)*8]),
                            wo_b=wb[:, lo*1024:(lo+groups)*1024].contiguous(),
                            wo_b_scale=scales(wbs[:, lo*8:(lo+groups)*8]),
                            out=torch.empty(count, 7168), scratch=scratch(name))
            launch(name, operands, [count])
            # Scratch follows live rows, not the capacity; grouped tmp is G,M,R.
            from b12x.integration.cuteafd.dsv4_wo import _layout
            from b12x.integration.cuteafd import PRO
            from dataclasses import replace
            geo = replace(PRO, o_groups=groups, heads=groups*8)
            geometry = entries[name]["geometry"]
            a_slices, b_slices = geometry["split_k_slices"]
            layout = _layout(geo, count, a_slices, b_slices)
            arena = operands["scratch"]
            def region(key, length, dtype):
                off = layout[key]
                size = torch.empty((), dtype=dtype).element_size()
                return arena[off:off+length*size].view(dtype)
            tmp = region("tmp", count*groups*1024, torch.bfloat16).reshape(groups, count, 1024).permute(1, 0, 2).contiguous()
            av = region("a_values", count*groups*4096, torch.float8_e4m3fn).reshape(groups, count, 4096)
